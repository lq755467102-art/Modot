export type UiMessage = keyof typeof english;
export type UiTranslator = (message: UiMessage, values?: Record<string, string | number>) => string;
export function isUiMessage(value: string): value is UiMessage {
  return Object.hasOwn(english, value);
}
export function translator(locale: "en" | "zh-CN"): UiTranslator {
  return (message, values) => {
    const text = locale === "en" ? english[message] : message;
    return values ? text.replace(/\{(\w+)\}/g, (original, name) => String(values[name] ?? original)) : text;
  };
}
