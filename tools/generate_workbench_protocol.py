from pathlib import Path
import json, sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from loop.workbench_protocol import SCHEMA


def ts(spec):
    if "anyOf" in spec:
        return " | ".join(ts(item) for item in spec["anyOf"])
    if "$ref" in spec:
        return spec["$ref"].split("/")[-1]
    if "enum" in spec:
        return " | ".join(json.dumps(v) for v in spec["enum"])
    t = spec.get("type")
    if isinstance(t, list):
        return " | ".join(ts({"type": v}) for v in t)
    if t == "array":
        return "(" + ts(spec["items"]) + ")[]"
    if t == "object" and isinstance(spec.get("additionalProperties"), dict):
        return "Record<string, " + ts(spec["additionalProperties"]) + ">"
    return {
        "number": "number",
        "string": "string",
        "boolean": "boolean",
        "null": "null",
        "object": "Record<string, unknown>",
    }.get(t, "unknown")


def generate():
    rows = ["// Generated by tools/generate_workbench_protocol.py. Do not edit."]
    for name, spec in SCHEMA["$defs"].items():
        rows.append("export interface " + name + " {")
        for key, kind in spec["properties"].items():
            rows.append(
                "  "
                + key
                + ("" if key in spec["required"] else "?")
                + ": "
                + ts(kind)
                + ";"
            )
        if spec.get("additionalProperties"):
            rows.append("  [key: string]: unknown;")
        rows.append("}")
    rows.append("export const WORKBENCH_SCHEMAS = " + json.dumps(SCHEMA["$defs"]) + ";")
    outputs = {
        "desktop/renderer-v2/src/generated.ts": "\n".join(rows) + "\n",
        "harness/workbench-v2.schema.json": json.dumps(SCHEMA, indent=2) + "\n",
    }
    for name, content in outputs.items():
        path = ROOT / name
        if "--check" in sys.argv:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit("Generated protocol out of date: " + name)
        else:
            path.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    generate()
