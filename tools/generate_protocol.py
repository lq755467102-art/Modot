"""Generate the frontend contract from loop.protocol. No third-party dependencies."""
import json
from pathlib import Path
import sys
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from loop.protocol import SCHEMA, PROTOCOL_VERSION

def ts(spec):
    if 'enum' in spec: return ' | '.join(json.dumps(v) for v in spec['enum'])
    t=spec.get('type')
    if isinstance(t,list): return ' | '.join(ts({'type':v}) for v in t)
    if t=='object': return 'Record<string, unknown>'
    return {'integer':'number','number':'number','string':'string','boolean':'boolean',
            'array':'unknown[]','null':'null'}.get(t,'unknown')

def generate():
    out=ROOT/'desktop/renderer/js'
    decl=['// Generated by tools/generate_protocol.py; do not edit.']
    for name,spec in SCHEMA['$defs'].items():
        decl.append('export interface '+name+' {')
        for field,kind in spec.get('properties',{}).items():
            decl.append('  '+field+('' if field in spec.get('required',[]) else '?')+': '+ts(kind)+';')
        decl.append('}')
    (out/'protocol.d.ts').write_text('\n'.join(decl)+'\n',encoding='utf-8')
    (ROOT/'harness/protocol.schema.json').write_text(json.dumps(SCHEMA,indent=2)+'\n',encoding='utf-8')
    validator='''// Generated by tools/generate_protocol.py; do not edit.
const HARNESS_PROTOCOL_VERSION = VERSION;
const HARNESS_SCHEMAS = SCHEMAS;
function validateProtocol(name, value) {
  const spec = HARNESS_SCHEMAS[name];
  if (!value || typeof value !== 'object' || Array.isArray(value)) return false;
  if ((spec.required || []).some(k => !(k in value))) return false;
  return Object.entries(spec.properties || {}).every(([k, s]) => {
    if (!(k in value)) return true;
    const v = value[k];
    if (s.enum) return s.enum.includes(v);
    return [].concat(s.type).some(t => t === 'null' ? v === null :
      t === 'integer' ? Number.isInteger(v) && (s.minimum === undefined || v >= s.minimum) :
      t === 'array' ? Array.isArray(v) : t === 'object' ? v !== null && typeof v === 'object' && !Array.isArray(v) : typeof v === t);
  });
}
'''
    validator=validator.replace('= VERSION;', '= '+str(PROTOCOL_VERSION)+';')
    (out/'protocol.js').write_text(validator.replace('= SCHEMAS;', '= '+json.dumps(SCHEMA['$defs'])+';'),encoding='utf-8')

if __name__=='__main__': generate()
